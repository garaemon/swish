#!/usr/bin/env bash
# Regenerate apps/web/lib/supabase/types.ts from the local Supabase schema.
# Pre-condition: `supabase start` has been run and migrations are applied.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TARGET="$DIR/apps/web/lib/supabase/types.ts"

# Write to a temp file first so a failure in `supabase gen types` (e.g. the
# stack is not running) leaves the existing types.ts intact.
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  echo "// Generated by supabase gen types — do not edit by hand."
  echo "// Run \`./scripts/db-types.sh\` to regenerate after a migration change."
  supabase gen types typescript --local
} > "$tmp"

mv "$tmp" "$TARGET"
echo "wrote $TARGET"
